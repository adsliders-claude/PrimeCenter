# Convertit le chemin Windows UNC en format URL pour XML
def unc_to_url(unc_path: str) -> str:
    """Convertit chemin UNC Windows en URL file:// pour XML PrimeCenter."""
    # \\server\share\folder → file:////server/share/folder
    clean = unc_path.replace("\\", "/")
    if clean.startswith("//"):
        return f"file:{clean}"
    elif clean.startswith("/"):
        return f"file://{clean}"
    else:
        return f"file:///{clean}"


