# WORKFLOW COMPLET: FILENAME → XML → NAS
# ============================================================

def traiter_fichier(
    filename: str,
    mode: str = "bat",
    sauvegarder: bool = True
) -> dict:
    """
    Workflow complet: parse le filename, crée le ticket XML, le sauvegarde.

    Args:
        filename:   Nom du fichier (ex: '012345_001_Vitrine_Orange02_1210x650mm_20ex.pdf')
        mode:       'bat' ou 'prod'
        sauvegarder: Sauvegarder le XML dans les rapports?

    Returns:
        {'success': bool, 'metadata': dict, 'xml_path': str, 'xml_content': str}
    """
    # 1. Extraire les métadonnées
    meta = parse_filename(filename)
    if not meta.valide:
        return {"success": False, "erreur": meta.erreur}

    # 2. Générer le ticket XML
    xml_content = creer_ticket_xml_entree(meta, mode=mode)

    # 3. Nom du fichier XML de sortie
    xml_filename = filename.replace(meta.extension, "_ENTREE.xml")
    xml_path = ""

    # 4. Sauvegarder dans les rapports
    if sauvegarder:
        date_str = datetime.now().strftime("%Y-%m-%d")
        rapport_dir = Path(DOSSIERS_NAS["rapports"]) / date_str

        try:
            rapport_dir.mkdir(parents=True, exist_ok=True)
            xml_path = str(rapport_dir / xml_filename)
            with open(xml_path, "w", encoding="utf-8") as f:
                f.write(xml_content)
            print(f"[OK] Ticket XML sauvegardé: {xml_path}")
        except Exception as e:
            print(f"[ATTENTION] Impossible de sauvegarder XML: {e}")
            print(f"[INFO] XML généré (non sauvegardé):\n{xml_content}")

    return {
        "success": True,
        "metadata": {
            "order_id": meta.order_id,
            "job_id": meta.job_id,
            "job_name": meta.job_name,
            "gang_name": meta.gang_name,
            "width_mm": meta.width_mm,
            "height_mm": meta.height_mm,
            "copies": meta.copies,
            "recette": meta.recette
        },
        "xml_path": xml_path,
        "xml_content": xml_content
    }


