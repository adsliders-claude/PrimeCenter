# LECTURE TICKET XML DE SORTIE
# ============================================================

def lire_ticket_sortie(xml_path: str) -> dict:
    """
    Parse un ticket XML de sortie généré par PrimeCenter.
    Extrait les informations utiles pour le dashboard et l'Agent LLM.

    Args:
        xml_path: Chemin vers le fichier XML de sortie

    Returns:
        Dictionnaire avec toutes les informations extraites
    """
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
    except ET.ParseError as e:
        return {"erreur": f"XML invalide: {e}"}

    result = {
        "version": root.get("version", "?"),
        "last_event": root.get("lastEvent", ""),
        "jobs": [],
        "layouts": []
    }

    # Parser chaque job
    for job in root.findall("job"):
        job_data = {
            "creation_time": job.get("creationTime", ""),
            "source": {},
            "media": {},
            "process": {},
            "info": {}
        }

        # Source
        source = job.find("source")
        if source is not None:
            filespec = source.findtext("filespec", "")
            job_data["source"] = {
                "filespec": filespec,
                "pages": source.findtext("pages", "1"),
                "copies": source.findtext("copies", "1")
            }

        # Media
        media = job.find("media")
        if media is not None:
            w = media.find("width")
            h = media.find("height")
            job_data["media"] = {
                "width_mm": w.text if w is not None else "",
                "height_mm": h.text if h is not None else ""
            }

        # Process
        process = job.find("process")
        if process is not None:
            job_data["process"] = {
                "recipe": process.findtext("recipe", ""),
                "gang": process.findtext("gang", "")
            }

        # Info
        info = job.find("info")
        if info is not None:
            job_data["info"] = {
                "order_id": info.findtext("orderID", ""),
                "job_id": info.findtext("jobID", ""),
                "job_name": info.findtext("jobName", ""),
                "customer_id": info.findtext("customerID", ""),
                "comment": info.findtext("comment", "")
            }

        result["jobs"].append(job_data)

    # Parser chaque layout (amalgame)
    for layout in root.findall("layout"):
        layout_data = {
            "name": layout.get("name", ""),
            "last_event": layout.get("lastEvent", ""),
            "info": {},
            "paths": {},
            "jobs_contents": []
        }

        # Info amalgame
        info = layout.find("info")
        if info is not None:
            stats = info.find("stats")
            layout_data["info"] = {
                "fill_ratio": info.findtext("fillRatio", ""),
                "area_m2": stats.findtext("area") if stats is not None else "",
                "waste_m2": stats.findtext("waste") if stats is not None else "",
                "media_name": info.findtext("mediaName", ""),
                "gang": info.findtext("gang", ""),
                "width_mm": info.findtext("width", ""),
                "height_mm": info.findtext("height", ""),
                "cropped": info.findtext("cropped", "false")
            }

        # Chemins fichiers générés
        paths = layout.find("paths")
        if paths is not None:
            output = paths.find("output")
            cut = paths.find("cut")
            layout_data["paths"] = {
                "print_file": output.text.strip() if output is not None else "",
                "cut_file": cut.text.strip() if cut is not None else "",
                "print_timestamp": output.get("timeStamp", "") if output is not None else "",
                "cut_timestamp": cut.get("timeStamp", "") if cut is not None else ""
            }

        # Contenu (positions des visuels)
        contents = layout.find("contents")
        if contents is not None:
            for job_in_layout in contents.findall("job"):
                job_content = {
                    "id": job_in_layout.get("id", ""),
                    "items": job_in_layout.get("items", ""),
                    "positions": []
                }
                for item in job_in_layout.findall("item"):
                    job_content["positions"].append({
                        "page": item.get("page", "1"),
                        "x": item.get("x", "0"),
                        "y": item.get("y", "0"),
                        "w": item.get("w", "0"),
                        "h": item.get("h", "0"),
                        "angle": item.get("angle", "0")
                    })
                layout_data["jobs_contents"].append(job_content)

        result["layouts"].append(layout_data)

    return result


