# GÉNÉRATION TICKET XML D'ENTRÉE
# ============================================================

def creer_ticket_xml_entree(
    metadata: JobMetadata,
    mode: str = "bat",
    include_preflight: bool = True
) -> str:
    """
    Génère un ticket XML d'entrée pour PrimeCenter.
    (Utilisé principalement pour PrimeCenter MAX futur)
    En PRO: utile pour documentation et futur upgrade.

    Args:
        metadata:          JobMetadata extrait du nom de fichier
        mode:              'bat' ou 'prod'
        include_preflight: Inclure la section preflight

    Returns:
        Contenu XML formaté (string)
    """
    # Chemin du fichier source
    input_file = f"{DOSSIERS_NAS['input']}\\{metadata.filename}"
    input_url = unc_to_url(input_file)

    # Heure de création
    now = datetime.now().strftime("%Y-%m-%dT%H:%M:%S")

    # Créer l'arbre XML
    ticket = ET.Element("ticket", version="1")

    # --- PARTIE JOB ---
    job = ET.SubElement(ticket, "job", creationTime=now)

    # Source
    source = ET.SubElement(job, "source")
    ET.SubElement(source, "filespec").text = input_url
    ET.SubElement(source, "pages").text = "1"
    ET.SubElement(source, "copies").text = str(metadata.copies)

    # Media (dimensions du visuel — sans fond perdu)
    media = ET.SubElement(job, "media")
    ET.SubElement(media, "width", unit="mm").text = str(metadata.width_mm)
    ET.SubElement(media, "height", unit="mm").text = str(metadata.height_mm)

    # Process (recette + ganging)
    process = ET.SubElement(job, "process")
    ET.SubElement(process, "recipe").text = metadata.recette
    # Ganging par matière (gangName = customerID dans PrimeCenter)
    gang = ET.SubElement(process, "gang")
    gang.set("by", "customerID")

    # Info (métadonnées)
    info = ET.SubElement(job, "info")
    ET.SubElement(info, "orderID").text = metadata.order_id
    ET.SubElement(info, "jobID").text = metadata.job_id
    ET.SubElement(info, "jobName").text = metadata.job_name
    # gangName → customerID (utilisé pour grouper par matière)
    ET.SubElement(info, "customerID").text = metadata.gang_name
    ET.SubElement(info, "comment").text = f"Mode:{mode.upper()} | AutoGenerated:{now[:10]}"

    # Preflight (optionnel)
    if include_preflight:
        preflights = ET.SubElement(job, "preflights")
        pf1 = ET.SubElement(preflights, "preflight1")
        ET.SubElement(pf1, "profile").text = "Verify_Colors_Resolution_Fonts"
        pf2 = ET.SubElement(preflights, "preflight2")
        ET.SubElement(pf2, "profile").text = "Fix_RGB_CMYK_FontEmbedding"

    # Formater en XML lisible
    xml_str = ET.tostring(ticket, encoding="unicode")
    dom = minidom.parseString(xml_str)
    return dom.toprettyxml(indent="  ", encoding=None).replace(
        '<?xml version="1.0" ?>', '<?xml version="1.0" encoding="UTF-8"?>'
    )


